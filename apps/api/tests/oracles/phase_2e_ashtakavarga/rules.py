def independent_bav(chart: IndependentChart, target_planet: str) -> List[int]:
    bav = [0] * 12
    for contributor, houses in BAV_RULES[target_planet].items():
        sign = chart.get_planet_sign_index(contributor)
        if sign is None:
            raise ValueError(f"Missing contributor {contributor}")
        for h in houses:
            idx = (sign + h - 2) % 12
            bav[idx] += 1
    return bav

def independent_sav(chart: IndependentChart) -> List[int]:
    sav = [0] * 12
    for p in ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn"]:
        bav = independent_bav(chart, p)
        for i in range(12):
            sav[i] += bav[i]
    return sav
