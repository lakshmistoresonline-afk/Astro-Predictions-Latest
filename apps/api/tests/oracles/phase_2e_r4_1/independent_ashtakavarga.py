def r4_independent_bav(chart: IndependentChart, target_planet: str) -> List[int]:
    target_sign = chart.planets[target_planet].sign_index # 1..12
    bindus = [0] * 12
    rules = BAV_RULES[target_planet]

    for contributor, beneficial_houses in rules.items():
        if contributor == "Ascendant":
            contrib_sign = chart.ascendant_sign_index
        else:
            contrib_sign = chart.planets[contributor].sign_index

        for house_offset in beneficial_houses:
            target_sign_index = (contrib_sign + house_offset - 2) % 12
            bindus[target_sign_index] += 1

    return bindus

def r4_independent_sav(chart: IndependentChart) -> List[int]:
    sav_bindus = [0] * 12
    for planet in ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn"]:
        bav = r4_independent_bav(chart, planet)
        for i in range(12):
            sav_bindus[i] += bav[i]
    return sav_bindus
